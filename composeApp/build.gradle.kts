// VER-01: one version for every platform, read from the catalog into a generated AppInfo object
val generateAppInfo by tasks.registering {
    val outputDir = layout.buildDirectory.dir("generated/appinfo/kotlin")
    val version = libs.versions.app.versionName.get()
    val code = libs.versions.app.versionCode.get()
    inputs.property("version", version)
    inputs.property("code", code)
    outputs.dir(outputDir)
    doLast {
        val file = outputDir.get().file("com/gondroid/subtrack/core/config/AppInfo.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |package com.gondroid.subtrack.core.config
            |
            |/** Generated by Gradle (composeApp/build.gradle.kts). Do not edit. */
            |object AppInfo {
            |    const val VERSION_NAME: String = "$version"
            |    const val VERSION_CODE: Int = $code
            |}
            |""".trimMargin(),
        )
    }
}

